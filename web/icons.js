/**
 * Render an icon as an inline SVG string.
 * @param {string} name  one of ICON_NAMES (unknown names render a circle placeholder)
 * @param {{size?: number, cls?: string}} opts
 * @returns {string} SVG markup
 */
export function icon(name, opts = {}) {
  const { size = 16, cls = '' } = opts || {};
  const body = (typeof name === 'string' && PATHS[name]) || FALLBACK;
  const className = ('icon ' + (cls || '')).trim();
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" ` +
    `fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ` +
    `class="${className}" aria-hidden="true">${body}</svg>`;
}

/**
 * Google S2 favicon URL for a site (the only remote icon source, opt-in per call).
 * Accepts full URLs or bare hosts ('github.com'); 'https://' is assumed when
 * the scheme is missing. Returns null when no hostname can be parsed.
 */
export function faviconUrl(siteUrl, size = 32) {
  if (!siteUrl || typeof siteUrl !== 'string') return null;
  let raw = siteUrl.trim();
  if (!raw) return null;
  if (!/^[a-zA-Z][a-zA-Z0-9+.-]*:\/\//.test(raw)) raw = 'https://' + raw;
  let hostname = '';
  try { hostname = new URL(raw).hostname; } catch { return null; }
  if (!hostname) return null;
  return `https://www.google.com/s2/favicons?domain=${hostname}&sz=${size}`;
}
